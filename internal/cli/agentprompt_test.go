package cli

import "testing"

func TestBuildAgentPromptWithContext(t *testing.T) {
	got := buildAgentPrompt("on-branch-main", "Summarize the repo.\n")
	want := "## Project context (generated by Runefile [context] task)\n" +
		"on-branch-main\n\n## Task\nSummarize the repo.\n"
	if got != want {
		t.Errorf("prompt =\n%q\nwant\n%q", got, want)
	}
}

func TestBuildAgentPromptWithoutContext(t *testing.T) {
	if got := buildAgentPrompt("", "Summarize.\n"); got != "Summarize.\n" {
		t.Errorf("no context: prompt must pass through unchanged, got %q", got)
	}
}
